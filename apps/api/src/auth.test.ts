import { users } from "@ts-todo/db/schema";
import { describe, expect, it } from "vitest";

import { cookieFrom, signedInCookie, signIn, signUp } from "../test/helpers";
import app from "./app";
import { db } from "./db";

const UUID_V7 = /^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;

describe("POST /auth/sign-up/email", () => {
	it("creates a user with a UUID v7 id generated by Postgres", async () => {
		const res = await signUp();

		expect(res.status).toBe(200);
		const rows = await db.select().from(users);
		expect(rows).toHaveLength(1);
		expect(rows[0]?.id).toMatch(UUID_V7);
	});

	it("stores the email in lowercase", async () => {
		await signUp({ email: "John@Example.com" });

		const rows = await db.select().from(users);
		expect(rows[0]?.email).toBe("john@example.com");
	});

	it("rejects a second sign-up with the same email in any casing", async () => {
		await signUp();

		const res = await signUp({ email: "JOHN@example.com" });

		expect(res.status).toBe(422);
		const rows = await db.select().from(users);
		expect(rows).toHaveLength(1);
	});
});

describe("POST /auth/sign-in/email", () => {
	it("returns a session cookie for correct credentials", async () => {
		await signUp();

		const res = await signIn();

		expect(res.status).toBe(200);
		expect(cookieFrom(res)).toContain("better-auth.session_token=");
	});

	it("accepts the email in any casing", async () => {
		await signUp();

		const res = await signIn({ email: "John@Example.COM" });

		expect(res.status).toBe(200);
	});

	it("rejects a wrong password", async () => {
		await signUp();

		const res = await signIn({ password: "wrong-password" });

		expect(res.status).toBe(401);
	});
});

describe("origin check", () => {
	it("rejects a cookie-authenticated request from an untrusted origin", async () => {
		const cookie = await signedInCookie();

		const res = await app.request("/auth/sign-out", {
			method: "POST",
			headers: {
				"Content-Type": "application/json",
				Origin: "https://evil.example",
				Cookie: cookie,
			},
			body: "{}",
		});

		expect(res.status).toBe(403);
	});
});
